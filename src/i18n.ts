const tables = { en, de };

export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function translator(lang: Lang): T {
  const table = tables[lang];
  const nf = new Intl.NumberFormat(lang === 'de' ? 'de-DE' : 'en-GB');
  return (key, vars) => {
    let s = table[key] ?? en[key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, typeof v === 'number' ? nf.format(v) : v);
    return s;
  };
}

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem('passer.lang');
    if (saved === 'en' || saved === 'de') return saved;
  } catch {
    /* storage blocked */
  }
  return navigator.language?.toLowerCase().startsWith('de') ? 'de' : 'en';
}

export const I18n = createContext<{ lang: Lang; t: T }>({ lang: 'en', t: translator('en') });
export const useI18n = () => useContext(I18n);
